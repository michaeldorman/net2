import net2

def test_pos():
    G = net2.data['roads']
    pos = net2.pos(G)
    assert pos == {0: [2000.0, 0.0], 1: [2000.0, 1000.0], 2: [3000.0, 1000.0], 3: [4000.0, 1000.0], 4: [2000.0, 2000.0], 5: [3000.0, 2000.0], 6: [0.0, 2000.0], 7: [1000.0, 2000.0], 8: [4000.0, 2000.0], 9: [2000.0, 3000.0], 10: [3000.0, 3000.0], 11: [4000.0, 3000.0], 12: [2000.0, 3500.0], 13: [500.0, 3500.0], 14: [3500.0, 2300.0], 15: [3500.0, 4000.0], 16: [2000.0, 4000.0]}, "error in 'net2.pos'"
